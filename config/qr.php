<?php

declare(strict_types=1);

/**
 * A small, self-contained QR Code encoder.
 *
 * WHY THIS EXISTS
 * ---------------
 * The report card has to carry a scannable "verify this result" code, and the
 * portal has no QR dependency: there is no Composer install, no vendor directory
 * and no GD or imagick extension available. Rather than ship a placeholder image
 * that only looks like a QR code, this file implements the parts of
 * ISO/IEC 18004 that a verification code actually needs:
 *
 *   - byte mode (the payload is a URL, so there is nothing to gain from trying
 *     to squeeze it into numeric or alphanumeric mode),
 *   - error correction level L or M,
 *   - versions 1 to 10, which carry up to 213 bytes at level M - far more than
 *     any verification URL needs,
 *   - all eight data masks, chosen by the standard penalty score,
 *   - format information and, from version 7, version information.
 *
 * WHAT IT DELIBERATELY DOES NOT DO
 * --------------------------------
 * It is not a general purpose library. Micro QR, ECI, structured append, Kanji
 * mode and the numeric/alphanumeric modes are all out of scope, because the only
 * caller is generateVerificationQRCode() and it always encodes one ASCII URL.
 *
 * The encoder was validated module-for-module against an independent reference
 * implementation (see tests/qr-verification-check.php), rather than against its
 * own output, so a mistake in placement or masking cannot pass unnoticed.
 */

/* ---------------------------------------------------------------------------
 * GF(256) arithmetic
 *
 * QR uses the field generated by the primitive polynomial x^8 + x^4 + x^3 + x^2
 * + 1, which is 0x11D. Addition is XOR and multiplication is carry-less with a
 * reduction by that polynomial.
 * ------------------------------------------------------------------------ */

/** Multiply two field elements. */
function qrFieldMultiply(int $a, int $b): int
{
    $product = 0;

    for ($i = 0; $b !== 0; $i++) {
        if (($b & 1) !== 0) {
            $product ^= $a;
        }

        $b >>= 1;
        $a <<= 1;

        if (($a & 0x100) !== 0) {
            $a ^= 0x11D;
        }
    }

    return $product;
}

/** Raise a field element to a power. */
function qrFieldPower(int $a, int $n): int
{
    $result = 1;

    while ($n > 0) {
        if (($n & 1) !== 0) {
            $result = qrFieldMultiply($result, $a);
        }

        $a = qrFieldMultiply($a, $a);
        $n >>= 1;
    }

    return $result;
}

/**
 * The generator polynomial for $degree error-correction codewords, which is the
 * product of (x - a^i) for i = 0 .. $degree-1. Indexed by power of x, so
 * $polynomial[0] is the constant term.
 */
function qrGeneratorPolynomial(int $degree): array
{
    /* Coefficient of x^0 first. Multiplying by (x - a^i) shifts the existing
       coefficients up one power and folds a^i into the lower term, so the
       constant term ends up holding the product of the roots. */
    $polynomial = [1];

    for ($i = 0; $i < $degree; $i++) {
        $root = qrFieldPower(2, $i);
        $next = array_fill(0, count($polynomial) + 1, 0);

        foreach ($polynomial as $index => $coefficient) {
            $next[$index]     ^= $coefficient;
            $next[$index + 1] ^= qrFieldMultiply($coefficient, $root);
        }

        $polynomial = $next;
    }

    return $polynomial;
}

/**
 * The Reed-Solomon remainder of $data against $generator: the error-correction
 * codewords that turn $data into a valid codeword of the longer block.
 */
function qrRemainder(array $data, array $generator): array
{
    $degree = count($generator) - 1;
    $result = array_fill(0, $degree, 0);

    foreach ($data as $byte) {
        $factor = $byte ^ $result[0];

        array_shift($result);
        $result[] = 0;

        for ($i = 0; $i < $degree; $i++) {
            $result[$i] ^= qrFieldMultiply($generator[$i + 1], $factor);
        }
    }

    return $result;
}

/* ---------------------------------------------------------------------------
 * Version tables
 *
 * [error correction codewords per block, then [block count, data codewords per
 * block] pairs - the second pair exists for versions whose blocks are not all
 * the same length].
 * ------------------------------------------------------------------------ */

/** @return array<string, array{0:int,1:array<int,array{0:int,1:int}>}> */
function qrBlockLayout(int $version, string $ecLevel): array
{
    static $table = [
        1  => ['L' => [7,  [[1, 19]]],         'M' => [10, [[1, 16]]]],
        2  => ['L' => [10, [[1, 34]]],         'M' => [16, [[1, 28]]]],
        3  => ['L' => [15, [[1, 55]]],         'M' => [26, [[1, 44]]]],
        4  => ['L' => [20, [[1, 80]]],         'M' => [18, [[2, 32]]]],
        5  => ['L' => [26, [[1, 108]]],        'M' => [24, [[2, 43]]]],
        6  => ['L' => [18, [[2, 68]]],         'M' => [16, [[4, 27]]]],
        7  => ['L' => [20, [[2, 78]]],         'M' => [18, [[4, 31]]]],
        8  => ['L' => [24, [[2, 97]]],         'M' => [22, [[2, 38], [2, 39]]]],
        9  => ['L' => [30, [[2, 116]]],        'M' => [22, [[3, 36], [2, 37]]]],
        10 => ['L' => [18, [[2, 68], [2, 69]]], 'M' => [26, [[4, 43], [1, 44]]]],
    ];

    if (!isset($table[$version][$ecLevel])) {
        throw new InvalidArgumentException('Unsupported QR version or error correction level.');
    }

    return $table[$version][$ecLevel];
}

/** Total number of data codewords a version holds at an error correction level. */
function qrDataCodewords(int $version, string $ecLevel): int
{
    [, $groups] = qrBlockLayout($version, $ecLevel);

    $total = 0;

    foreach ($groups as [$count, $length]) {
        $total += $count * $length;
    }

    return $total;
}

/** Row and column centres of the alignment patterns for a version. */
function qrAlignmentCentres(int $version): array
{
    static $table = [
        1 => [], 2 => [6, 18], 3 => [6, 22], 4 => [6, 26], 5 => [6, 30],
        6 => [6, 34], 7 => [6, 22, 38], 8 => [6, 24, 42], 9 => [6, 26, 46],
        10 => [6, 28, 50],
    ];

    return $table[$version] ?? [];
}

/**
 * Byte-mode capacity, in bytes, for a version at an error correction level.
 * The header is a four bit mode indicator plus the character count, which is
 * eight bits up to version 9 and sixteen bits from version 10.
 */
function qrByteCapacity(int $version, string $ecLevel): int
{
    $countBits = $version <= 9 ? 8 : 16;

    return intdiv(qrDataCodewords($version, $ecLevel) * 8 - 4 - $countBits, 8);
}

/* ---------------------------------------------------------------------------
 * Encoding
 * ------------------------------------------------------------------------ */

/**
 * Turn the payload into the final interleaved stream of data and
 * error-correction codewords.
 *
 * @return array<int,int>
 */
function qrCodewords(string $text, int $version, string $ecLevel): array
{
    [$ecPerBlock, $groups] = qrBlockLayout($version, $ecLevel);

    $capacityBits = qrDataCodewords($version, $ecLevel) * 8;

    /* Mode indicator 0100 is byte mode. */
    $bits = '0100';

    $countBits = $version <= 9 ? 8 : 16;
    $bits     .= str_pad(decbin(strlen($text)), $countBits, '0', STR_PAD_LEFT);

    for ($i = 0, $length = strlen($text); $i < $length; $i++) {
        $bits .= str_pad(decbin(ord($text[$i])), 8, '0', STR_PAD_LEFT);
    }

    if (strlen($bits) > $capacityBits) {
        throw new RuntimeException('QR payload does not fit the chosen version.');
    }

    /* Terminator: up to four zero bits, then pad out to a byte boundary. */
    $bits .= str_repeat('0', min(4, $capacityBits - strlen($bits)));

    while (strlen($bits) % 8 !== 0) {
        $bits .= '0';
    }

    /* The two alternating pad codewords the specification requires. */
    $pad = 0;

    while (strlen($bits) < $capacityBits) {
        $bits .= $pad % 2 === 0 ? '11101100' : '00010001';
        $pad++;
    }

    $data = [];

    for ($i = 0, $length = strlen($bits); $i < $length; $i += 8) {
        $data[] = bindec(substr($bits, $i, 8));
    }

    /* Split into blocks and compute each block's own error correction. */
    $generator  = qrGeneratorPolynomial($ecPerBlock);
    $blocks     = [];
    $correction = [];
    $offset     = 0;

    foreach ($groups as [$count, $length]) {
        for ($i = 0; $i < $count; $i++) {
            $block         = array_slice($data, $offset, $length);
            $offset        += $length;
            $blocks[]      = $block;
            $correction[]  = qrRemainder($block, $generator);
        }
    }

    /* Interleave: every block contributes its first codeword, then its second,
       and so on, so that a burst of damage is spread across all blocks. The
       correction codewords follow the same rule. */
    $interleaved = [];

    $longest = 0;

    foreach ($blocks as $block) {
        $longest = max($longest, count($block));
    }

    for ($i = 0; $i < $longest; $i++) {
        foreach ($blocks as $block) {
            if (isset($block[$i])) {
                $interleaved[] = $block[$i];
            }
        }
    }

    for ($i = 0; $i < $ecPerBlock; $i++) {
        foreach ($correction as $block) {
            $interleaved[] = $block[$i];
        }
    }

    return $interleaved;
}

/** True when the module at (row, column) must be dark for mask $mask. */
function qrMaskApplies(int $mask, int $row, int $column): bool
{
    switch ($mask) {
        case 0: return ($row + $column) % 2 === 0;
        case 1: return $row % 2 === 0;
        case 2: return $column % 3 === 0;
        case 3: return ($row + $column) % 3 === 0;
        case 4: return (intdiv($row, 2) + intdiv($column, 3)) % 2 === 0;
        case 5: return (($row * $column) % 2) + (($row * $column) % 3) === 0;
        case 6: return ((($row * $column) % 2) + (($row * $column) % 3)) % 2 === 0;
        case 7: return (((($row + $column) % 2) + (($row * $column) % 3)) % 2) === 0;
    }

    return false;
}

/**
 * The standard penalty score. A lower score means a code that is easier for a
 * scanner to lock onto, which is why all eight masks are tried.
 */
function qrPenalty(array $modules, int $size): int
{
    $penalty = 0;

    /* Rule 1: runs of five or more modules of the same colour. */
    foreach ([true, false] as $horizontal) {
        for ($a = 0; $a < $size; $a++) {
            $run    = 1;
            $colour = $horizontal ? $modules[$a][0] : $modules[0][$a];

            for ($b = 1; $b < $size; $b++) {
                $next = $horizontal ? $modules[$a][$b] : $modules[$b][$a];

                if ($next === $colour) {
                    $run++;

                    if ($run === 5) {
                        $penalty += 3;
                    } elseif ($run > 5) {
                        $penalty++;
                    }
                } else {
                    $colour = $next;
                    $run    = 1;
                }
            }
        }
    }

    /* Rule 2: every 2x2 block of one colour. */
    for ($row = 0; $row < $size - 1; $row++) {
        for ($column = 0; $column < $size - 1; $column++) {
            $colour = $modules[$row][$column];

            if ($colour === $modules[$row][$column + 1]
                && $colour === $modules[$row + 1][$column]
                && $colour === $modules[$row + 1][$column + 1]) {
                $penalty += 3;
            }
        }
    }

    /* Rule 3: finder-like patterns, which a scanner can mistake for the real
       finder pattern: 1:1:3:1:1 with four light modules on one side. */
    $needles = ['10111010000', '00001011101'];

    foreach ([true, false] as $horizontal) {
        for ($a = 0; $a < $size; $a++) {
            $line = '';

            for ($b = 0; $b < $size; $b++) {
                $line .= $horizontal ? ($modules[$a][$b] ? '1' : '0') : ($modules[$b][$a] ? '1' : '0');
            }

            foreach ($needles as $needle) {
                $penalties = 0;
                $offset    = 0;

                while (($found = strpos($line, $needle, $offset)) !== false) {
                    $penalties++;
                    $offset = $found + 1;
                }

                $penalty += $penalties * 40;
            }
        }
    }

    /* Rule 4: how far the ratio of dark modules is from one half. */
    $dark = 0;

    for ($row = 0; $row < $size; $row++) {
        foreach ($modules[$row] as $module) {
            if ($module) {
                $dark++;
            }
        }
    }

    $total = $size * $size;
    $steps = intdiv(abs($dark * 20 - $total * 10) + $total - 1, $total) - 1;

    return $penalty + $steps * 10;
}

/**
 * Encode $text and return the finished symbol.
 *
 * @return array{
 *     size:int,
 *     modules:array<int,array<int,bool>>,
 *     version:int,
 *     mask:int,
 *     ecLevel:string
 * }
 */
function qrEncode(
    string $text,
    string $ecLevel = 'M',
    ?int $forcedMask = null,
    ?int $forcedVersion = null
): array {
    $ecLevel = strtoupper($ecLevel);

    if (!in_array($ecLevel, ['L', 'M'], true)) {
        throw new InvalidArgumentException('QR error correction level must be L or M.');
    }

    if ($text === '') {
        throw new InvalidArgumentException('QR payload must not be empty.');
    }

    if ($forcedVersion !== null) {
        if ($forcedVersion < 1 || $forcedVersion > 10) {
            throw new InvalidArgumentException('QR version must be between 1 and 10.');
        }

        if (strlen($text) > qrByteCapacity($forcedVersion, $ecLevel)) {
            throw new RuntimeException('QR payload does not fit the chosen version.');
        }

        $version = $forcedVersion;
    } else {
        $version = null;

        for ($candidate = 1; $candidate <= 10; $candidate++) {
            if (strlen($text) <= qrByteCapacity($candidate, $ecLevel)) {
                $version = $candidate;
                break;
            }
        }

        if ($version === null) {
            throw new RuntimeException('QR payload is too long to encode.');
        }
    }

    $size = 17 + 4 * $version;

    $modules  = [];
    $reserved = [];

    for ($row = 0; $row < $size; $row++) {
        for ($column = 0; $column < $size; $column++) {
            $modules[$row][$column]  = false;
            $reserved[$row][$column] = false;
        }
    }

    $reserve = static function (int $row, int $column) use (&$reserved, $size): void {
        if ($row >= 0 && $row < $size && $column >= 0 && $column < $size) {
            $reserved[$row][$column] = true;
        }
    };

    /* Writing a module the same guarded way. The finder patterns are drawn from
       a centre that sits four modules in from the edge, so the white separator
       ring falls one module outside the symbol and has to be discarded rather
       than allowed to add columns to the grid. */
    $set = static function (int $row, int $column, bool $value) use (&$modules, $size): void {
        if ($row >= 0 && $row < $size && $column >= 0 && $column < $size) {
            $modules[$row][$column] = $value;
        }
    };

    /* Finder patterns and their separators. */
    foreach ([[3, 3], [$size - 4, 3], [3, $size - 4]] as [$centreY, $centreX]) {
        for ($dy = -4; $dy <= 4; $dy++) {
            for ($dx = -4; $dx <= 4; $dx++) {
                $distance = max(abs($dx), abs($dy));
                $dark     = $distance !== 4 && $distance !== 2;

                $set($centreY + $dy, $centreX + $dx, $dark);
                $reserve($centreY + $dy, $centreX + $dx);
            }
        }
    }

    /* Alignment patterns, skipping the three corners the finders already own. */
    $centres = qrAlignmentCentres($version);

    foreach ($centres as $i => $centreY) {
        foreach ($centres as $j => $centreX) {
            $isFinderCorner = ($i === 0 && $j === 0)
                || ($i === 0 && $j === count($centres) - 1)
                || ($i === count($centres) - 1 && $j === 0);

            if ($isFinderCorner) {
                continue;
            }

            for ($dy = -2; $dy <= 2; $dy++) {
                for ($dx = -2; $dx <= 2; $dx++) {
                    $set($centreY + $dy, $centreX + $dx, max(abs($dx), abs($dy)) !== 1);
                    $reserve($centreY + $dy, $centreX + $dx);
                }
            }
        }
    }

    /* Timing patterns. */
    for ($i = 8; $i < $size - 8; $i++) {
        $modules[6][$i] = $i % 2 === 0;
        $modules[$i][6] = $i % 2 === 0;
        $reserve(6, $i);
        $reserve($i, 6);
    }

    /* Reserve both copies of the format information, plus the always-dark module. */
    for ($i = 0; $i <= 5; $i++) {
        $reserve($i, 8);
    }

    $reserve(7, 8);
    $reserve(8, 8);
    $reserve(8, 7);

    for ($i = 9; $i < 15; $i++) {
        $reserve(8, 14 - $i);
    }

    for ($i = 0; $i < 8; $i++) {
        $reserve(8, $size - 1 - $i);
    }

    for ($i = 8; $i < 15; $i++) {
        $reserve($size - 15 + $i, 8);
    }

    $reserve($size - 8, 8);

    /* Version information, from version 7 upwards. This is not the version
       number written out plainly: it is a BCH(18,6) code, the six version bits
       followed by a twelve bit remainder computed with the generator 0x1F25. */
    if ($version >= 7) {
        $remainder = $version;

        for ($i = 0; $i < 12; $i++) {
            $remainder = ($remainder << 1) ^ (($remainder >> 11) * 0x1F25);
        }

        $versionBits = ($version << 12) | $remainder;

        for ($i = 0; $i < 18; $i++) {
            $bit = (($versionBits >> $i) & 1) === 1;

            $a = $size - 11 + $i % 3;
            $b = intdiv($i, 3);

            $modules[$b][$a] = $bit;
            $modules[$a][$b] = $bit;
            $reserve($b, $a);
            $reserve($a, $b);
        }
    }

    /* Walk the data in the two-module-wide zigzag that starts at the bottom
       right corner, upward first, skipping the vertical timing column. */
    $codewords = qrCodewords($text, $version, $ecLevel);
    $bitIndex  = 0;
    $totalBits = count($codewords) * 8;
    $upward    = true;

    for ($column = $size - 1; $column > 0; $column -= 2) {
        if ($column === 6) {
            $column = 5;
        }

        for ($step = 0; $step < $size; $step++) {
            $row = $upward ? $size - 1 - $step : $step;

            for ($offset = 0; $offset < 2; $offset++) {
                $x = $column - $offset;

                if ($reserved[$row][$x]) {
                    continue;
                }

                $modules[$row][$x] = $bitIndex < $totalBits
                    && (($codewords[$bitIndex >> 3] >> (7 - ($bitIndex & 7))) & 1) === 1;

                $bitIndex++;
            }
        }

        $upward = !$upward;
    }

    /* Try every mask and keep the one the standard scores as easiest to read. */
    $chosen = 0;

    if ($forcedMask !== null) {
        $chosen = $forcedMask;
    } else {
        $bestPenalty = PHP_INT_MAX;

        for ($mask = 0; $mask < 8; $mask++) {
            $candidate = $modules;

            for ($row = 0; $row < $size; $row++) {
                for ($x = 0; $x < $size; $x++) {
                    if (!$reserved[$row][$x] && qrMaskApplies($mask, $row, $x)) {
                        $candidate[$row][$x] = !$candidate[$row][$x];
                    }
                }
            }

            $penalty = qrPenalty($candidate, $size);

            if ($penalty < $bestPenalty) {
                $bestPenalty = $penalty;
                $chosen      = $mask;
            }
        }
    }

    /* Apply the chosen mask to every data module, leaving the finder, timing,
       alignment and reserved areas untouched. */
    for ($row = 0; $row < $size; $row++) {
        for ($x = 0; $x < $size; $x++) {
            if (!$reserved[$row][$x] && qrMaskApplies($chosen, $row, $x)) {
                $modules[$row][$x] = !$modules[$row][$x];
            }
        }
    }

    /* Format information: two bits of error correction level, three of mask, a
       10 bit BCH remainder, then the standard 0x5412 mask. */
    $levelBits = ['L' => 1, 'M' => 0, 'Q' => 3, 'H' => 2][$ecLevel];
    $data      = ($levelBits << 3) | $chosen;
    $remainder = $data;

    for ($i = 0; $i < 10; $i++) {
        $remainder = ($remainder << 1) ^ (($remainder >> 9) * 0x537);
    }

    $bits = (($data << 10) | $remainder) ^ 0x5412;

    $bitAt = static function (int $index) use ($bits): bool {
        return (($bits >> $index) & 1) === 1;
    };

    for ($i = 0; $i <= 5; $i++) {
        $modules[$i][8] = $bitAt($i);
    }

    $modules[7][8] = $bitAt(6);
    $modules[8][8] = $bitAt(7);
    $modules[8][7] = $bitAt(8);

    for ($i = 9; $i < 15; $i++) {
        $modules[8][14 - $i] = $bitAt($i);
    }

    for ($i = 0; $i < 8; $i++) {
        $modules[8][$size - 1 - $i] = $bitAt($i);
    }

    for ($i = 8; $i < 15; $i++) {
        $modules[$size - 15 + $i][8] = $bitAt($i);
    }

    $modules[$size - 8][8] = true;

    return [
        'size'    => $size,
        'modules' => $modules,
        'version' => $version,
        'mask'    => $chosen,
        'ecLevel' => $ecLevel,
    ];
}

/**
 * Render an encoded symbol as an SVG.
 *
 * Every module is emitted into a single path rather than as one <rect> each, so
 * the output stays small enough to sit inline in a data URI. The colour is the
 * report card's deep green, which keeps the sheet's green and white identity
 * while staying dark enough for a scanner to read reliably.
 */
function qrSvg(array $symbol, string $foreground = '#0b3d2c', string $background = '#ffffff', int $moduleSize = 4, int $quietZone = 4): string
{
    $size      = (int) $symbol['size'];
    $modules   = $symbol['modules'];
    $side      = ($size + 2 * $quietZone) * $moduleSize;

    $path = '';

    for ($row = 0; $row < $size; $row++) {
        for ($column = 0; $column < $size; $column++) {
            if (!$modules[$row][$column]) {
                continue;
            }

            $x = ($column + $quietZone) * $moduleSize;
            $y = ($row + $quietZone) * $moduleSize;

            $path .= 'M' . $x . ' ' . $y . 'h' . $moduleSize . 'v' . $moduleSize . 'h-' . $moduleSize . 'z';
        }
    }

    if ($path === '') {
        throw new RuntimeException('QR symbol produced no modules.');
    }

    $pixels = $side;

    return '<svg xmlns="http://www.w3.org/2000/svg" width="' . $pixels . '" height="' . $pixels . '"'
        . ' viewBox="0 0 ' . $side . ' ' . $side . '" shape-rendering="crispEdges" role="img">'
        . '<rect width="' . $side . '" height="' . $side . '" fill="' . htmlspecialchars($background, ENT_QUOTES, 'UTF-8') . '"/>'
        . '<path d="' . $path . '" fill="' . htmlspecialchars($foreground, ENT_QUOTES, 'UTF-8') . '"/>'
        . '</svg>';
}